def grad_major_names(level, college_name):
    """返回某学院某层次的专业名集合（学硕+专硕合并，用于迁移匹配）。"""
    names = set()
    for track in GRAD_MAJORS.get(level, {}).values():
        for col, majors in track:
            if col == college_name:
                names.update(name for name, _code in majors)
    return names
